// Generates src/abi.ts (a typed `as const` copy of the verified fixture ABI) — run after a fixture change.
//   node scripts/gen-abi.mjs           write
//   node scripts/gen-abi.mjs --check   exit 1 if src/abi.ts does not match the fixture
import { readFileSync, writeFileSync } from 'node:fs'
const art = JSON.parse(readFileSync(new URL('../fixtures/SwapERC20.json', import.meta.url)))
const out = `// GENERATED by scripts/gen-abi.mjs from fixtures/SwapERC20.json (AirSwap SwapERC20 v5.0.0). Do not edit.
export const swapErc20Abi = ${JSON.stringify(art.abi, null, 2)} as const
`
const file = new URL('../src/abi.ts', import.meta.url)
if (process.argv.includes('--check')) {
  const cur = readFileSync(file, 'utf8')
  if (cur !== out) { console.error('src/abi.ts is out of date: run node scripts/gen-abi.mjs'); process.exit(1) }
  console.log('src/abi.ts matches the fixture ABI')
} else writeFileSync(file, out)
